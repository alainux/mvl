import type {
  BuilderSelection,
  DescribableThing, PresencePlace, PresenceThing, Quality, ObjectQuestionPredicate,
  Expression,
  LanguageProfile,
  LocatablePlace,
  Participant,
  PricedThing,
  Tense,
} from '../core/model.js';
import type { PredicateId, SemanticArgument } from '../core/vocabulary.js';
import type { Connection } from '../core/model.js';

/** Social conventions are the only stored complete expressions. */
export type RoutineId =
  | 'hello' | 'good_morning' | 'goodbye' | 'thank_you'
  | 'you_are_welcome' | 'excuse_me' | 'yes' | 'no'
  | 'slowly' | 'learning';

/** Shared lesson plans describe productive operations, never sentence pairs. */
export type LessonBlock =
  | Readonly<{
      kind: 'paradigm';
      predicate: PredicateId;
      agent: Participant;
      arguments: readonly SemanticArgument[];
      options?: Partial<Omit<BuilderSelection, 'predicate' | 'agent' | 'argument'>>;
    }>
  | Readonly<{
      kind: 'timeline';
      predicate: PredicateId;
      agent: Participant;
      arguments: readonly SemanticArgument[];
      tenses: readonly Tense[];
      options?: Partial<Omit<BuilderSelection, 'predicate' | 'agent' | 'argument' | 'tense' | 'time'>>;
    }>
  | Readonly<{ kind: 'when-question'; predicate: PredicateId; agent: Participant; argument: SemanticArgument; } >
  | Readonly<{
      kind: 'combine';
      connection: Connection;
      first: Partial<BuilderSelection> & Pick<BuilderSelection, 'predicate' | 'agent' | 'argument'>;
      second: Partial<BuilderSelection> & Pick<BuilderSelection, 'predicate' | 'agent' | 'argument'>;
    }>
  | Readonly<{ kind: 'where'; places: readonly LocatablePlace[] }>
  | Readonly<{ kind: 'price'; things: readonly PricedThing[] }>
  | Readonly<{
      kind: 'describe';
      thing: DescribableThing;
      qualities: readonly Quality[];
      options?: Readonly<{ tense?: 'present' | 'past'; negative?: boolean; question?: boolean }>;
    }>
  | Readonly<{
      kind: 'presence';
      things: readonly PresenceThing[];
      places: readonly (PresencePlace | null)[];
      options?: Readonly<{ negative?: boolean; question?: boolean }>;
    }>
  | Readonly<{
      kind: 'ask-object';
      predicates: readonly ObjectQuestionPredicate[];
      agent: 'speaker' | 'addressee';
    }>
  | Readonly<{ kind: 'route'; places: readonly LocatablePlace[] }>
  | Readonly<{
      kind: 'sequence';
      steps: readonly (Partial<BuilderSelection> & Pick<BuilderSelection, 'predicate' | 'agent' | 'argument'>)[];
    }>
  | Readonly<{ kind: 'conventions'; ids: readonly RoutineId[] }>;

export type ExampleSource =
  | Readonly<{ kind: 'expression'; expression: Expression; selection?: BuilderSelection }>
  | Readonly<{ kind: 'convention'; routine: RoutineId }>;

export type LessonId =
  | 'first-words' | 'identity' | 'needs' | 'questions' | 'negation'
  | 'places' | 'routines' | 'ability' | 'obligation' | 'present-time'
  | 'past' | 'past-movement' | 'future' | 'plans' | 'people'
  | 'shopping' | 'problems' | 'reasons' | 'small-story' | 'combine'
  | 'open-questions' | 'habits' | 'preferences' | 'description'
  | 'housing' | 'services-nearby' | 'directions' | 'food-services'
  | 'work-and-study' | 'digital-life' | 'forms' | 'health'
  | 'appointments' | 'social-life' | 'lost-property' | 'travel-delays'
  | 'more-past' | 'more-future' | 'stories' | 'independent-life';

export type Stage = 'foundation' | 'time-and-plans' | 'connected-speech' | 'everyday-life' | 'independent-speech';

export interface LessonDefinition {
  readonly id: LessonId;
  readonly stage: Stage;
  readonly title: string;
  readonly goal: string;
  readonly introduction: string;
  readonly blocks: readonly LessonBlock[];
}

/** Notes explain the rule; productive forms are always generated by the AST. */
export interface LessonNotes {
  readonly recipe: string;
  readonly explanation: string;
  readonly detail: string;
  readonly caution: string;
}

export interface GeneratedExample {
  readonly id: string;
  readonly english: string;
  readonly target: string;
  readonly source: ExampleSource;
  readonly provenance: 'composed' | 'conventional';
}

export interface GeneratedLesson extends Omit<LessonDefinition, 'blocks'> {
  readonly notes: LessonNotes;
  readonly examples: readonly GeneratedExample[];
}

export interface GeneratedGuide {
  readonly language: LanguageProfile;
  readonly lessons: readonly GeneratedLesson[];
}
